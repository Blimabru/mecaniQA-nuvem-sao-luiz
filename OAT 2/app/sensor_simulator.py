import json
import os
import random
import threading
import time
from http.server import BaseHTTPRequestHandler, HTTPServer

from prometheus_client import CONTENT_TYPE_LATEST, Counter, Gauge, generate_latest

SERVICE_NAME = os.getenv("SERVICE_NAME", "sensor-simulator")
PORT = int(os.getenv("PORT", "8000"))
ERROR_RATE = float(os.getenv("SENSOR_ERROR_RATE", "0.05"))
INTERVAL_SECONDS = float(os.getenv("SENSOR_INTERVAL_SECONDS", "2"))

TEMPERATURE = Gauge(
    "sensor_temperature_celsius",
    "Current temperature reading in Celsius for the simulated vehicle sensor.",
    labelnames=("sensor",),
)
VIBRATION = Gauge(
    "sensor_vibration_mm_s",
    "Current vibration reading in millimeters per second.",
    labelnames=("sensor",),
)
PRESSURE = Gauge(
    "sensor_pressure_kpa",
    "Current pressure reading in kilopascal.",
    labelnames=("sensor",),
)
HEALTH = Gauge(
    "sensor_health",
    "Sensor health status; 1 is healthy and 0 indicates a faulty reading.",
    labelnames=("sensor",),
)
ERROR_RATE_GAUGE = Gauge(
    "sensor_error_rate",
    "Configured rate of synthetic sensor failures used in the simulator.",
    labelnames=("sensor",),
)
READINGS_TOTAL = Counter(
    "sensor_readings_total",
    "Total number of readings generated by the simulator.",
    labelnames=("sensor", "status"),
)


def emit_reading() -> None:
    sensor_name = "motor-01"
    should_error = random.random() < ERROR_RATE

    temperature_value = random.uniform(72.0, 98.0)
    vibration_value = random.uniform(0.5, 1.8)
    pressure_value = random.uniform(30.0, 35.0)

    if should_error:
        temperature_value = random.uniform(105.0, 130.0)
        vibration_value = random.uniform(2.2, 4.0)
        pressure_value = random.uniform(38.0, 52.0)
        status = "error"
        HEALTH.labels(sensor_name).set(0)
    else:
        status = "ok"
        HEALTH.labels(sensor_name).set(1)

    TEMPERATURE.labels(sensor_name).set(temperature_value)
    VIBRATION.labels(sensor_name).set(vibration_value)
    PRESSURE.labels(sensor_name).set(pressure_value)
    ERROR_RATE_GAUGE.labels(sensor_name).set(ERROR_RATE)
    READINGS_TOTAL.labels(sensor_name, status).inc()


class SensorHandler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:
        if self.path in ("/", ""):
            payload = {
                "status": "UP",
                "service": SERVICE_NAME,
                "message": "Sensor simulator is running",
            }
            body = json.dumps(payload).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return

        if self.path == "/health":
            payload = {
                "status": "UP",
                "service": SERVICE_NAME,
                "error_rate": ERROR_RATE,
                "interval_seconds": INTERVAL_SECONDS,
                "port": PORT,
            }
            body = json.dumps(payload).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return

        if self.path == "/metrics":
            payload = generate_latest()
            self.send_response(200)
            self.send_header("Content-Type", CONTENT_TYPE_LATEST)
            self.send_header("Content-Length", str(len(payload)))
            self.end_headers()
            self.wfile.write(payload)
            return

        self.send_response(404)
        self.end_headers()

    def log_message(self, format: str, *args) -> None:
        return


def run_server() -> None:
    server = HTTPServer(("0.0.0.0", PORT), SensorHandler)
    print(f"sensor simulator listening on http://0.0.0.0:{PORT}")
    server.serve_forever()


def background_worker() -> None:
    while True:
        emit_reading()
        time.sleep(INTERVAL_SECONDS)


if __name__ == "__main__":
    HEALTH.labels("motor-01").set(1)
    ERROR_RATE_GAUGE.labels("motor-01").set(ERROR_RATE)
    thread = threading.Thread(target=background_worker, daemon=True)
    thread.start()
    run_server()
